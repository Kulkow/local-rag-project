import { createApp } from 'vue';
import { createPinia } from 'pinia';
import { createRouter, createWebHistory } from 'vue-router';
import PrimeVue from 'primevue/config';
import Aura from '@primevue/themes/aura';
import App from './App.vue';
import Dashboard from './modules/operations/presentation/DashboardView.vue';
import Families from './modules/families/presentation/FamiliesView.vue';
import Users from './modules/identity/presentation/UsersView.vue';
import Documents from './modules/documents/presentation/DocumentsView.vue';
import RagPlayground from './modules/rag/presentation/RagPlayground.vue';
import './style.css';
import { useAuth } from './modules/identity';
const router = createRouter({ history: createWebHistory(), scrollBehavior: to => to.hash ? { el: to.hash, top: 16 } : { top: 0 }, routes: [{path: '/', component: Dashboard}, {path: '/families', component: Families}, {path: '/users', component: Users}, {path: '/documents', component: Documents}, {path: '/rag', component: RagPlayground}, {path: '/:pathMatch(.*)*', redirect: '/'}] });
const pinia = createPinia();
createApp(App).use(pinia).use(router).use(PrimeVue, {theme: {preset: Aura}}).mount('#app');
const auth = useAuth(pinia);
window.addEventListener('auth:unauthorized', event => auth.invalidate((event as CustomEvent<string>).detail, 'Токен истёк или отозван. Войдите снова.'));
void auth.restore();
